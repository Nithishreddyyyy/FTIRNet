import torch.nn as nn

# =========================================================
# FTIR CNN
# =========================================================

class FTIRCNN(nn.Module):

    def __init__(self, input_size, num_classes):

        super().__init__()

        # -------------------------------------------------
        # CONV BLOCK 1
        # -------------------------------------------------

        self.conv1 = nn.Conv1d(
            in_channels=1,
            out_channels=16,
            kernel_size=5,
            padding=2
        )

        self.bn1 = nn.BatchNorm1d(16)

        # -------------------------------------------------
        # CONV BLOCK 2
        # -------------------------------------------------

        self.conv2 = nn.Conv1d(
            in_channels=16,
            out_channels=32,
            kernel_size=5,
            padding=2
        )

        self.bn2 = nn.BatchNorm1d(32)

        # -------------------------------------------------
        # CONV BLOCK 3
        # -------------------------------------------------

        self.conv3 = nn.Conv1d(
            in_channels=32,
            out_channels=64,
            kernel_size=3,
            padding=1
        )

        self.bn3 = nn.BatchNorm1d(64)

        # -------------------------------------------------
        # ACTIVATION + POOL
        # -------------------------------------------------

        self.relu = nn.ReLU()

        self.pool = nn.MaxPool1d(2)

        # -------------------------------------------------
        # GLOBAL AVERAGE POOLING
        # -------------------------------------------------

        self.gap = nn.AdaptiveAvgPool1d(1)

        # -------------------------------------------------
        # DROPOUT
        # -------------------------------------------------

        self.dropout = nn.Dropout(0.35)

        # -------------------------------------------------
        # CLASSIFIER
        # -------------------------------------------------

        self.fc1 = nn.Linear(64, 128)

        self.fc2 = nn.Linear(
            128,
            num_classes
        )

    # =====================================================
    # FORWARD
    # =====================================================

    def forward(self, x):

        # -------------------------------------------------
        # BLOCK 1
        # -------------------------------------------------

        x = self.conv1(x)
        x = self.bn1(x)
        x = self.relu(x)
        x = self.pool(x)

        # -------------------------------------------------
        # BLOCK 2
        # -------------------------------------------------

        x = self.conv2(x)
        x = self.bn2(x)
        x = self.relu(x)
        x = self.pool(x)

        # -------------------------------------------------
        # BLOCK 3
        # -------------------------------------------------

        x = self.conv3(x)
        x = self.bn3(x)
        x = self.relu(x)
        x = self.pool(x)

        # -------------------------------------------------
        # GLOBAL AVERAGE POOLING
        # -------------------------------------------------

        x = self.gap(x)

        # -------------------------------------------------
        # FLATTEN
        # -------------------------------------------------

        x = x.squeeze(-1)

        # -------------------------------------------------
        # FC
        # -------------------------------------------------

        x = self.dropout(x)

        x = self.fc1(x)

        x = self.relu(x)

        x = self.dropout(x)

        x = self.fc2(x)

        return x
